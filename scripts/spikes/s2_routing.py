"""Technical Spike S2: DEM Slope & Land-Cover Cost-Surface 11 kV Feeder Routing.

Loads the Koraput (Nandapur Block) 30m DEM and ESA WorldCover rasters generated by S1,
builds the traversal cost surface, and routes preliminary 11 kV feeders from the
Bheja Main Village Tie-In Point to Podapadar Tola and Maliaguda PVTG Hamlet using
scikit-image MCP_Geometric.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import rasterio

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "backend"))

from app.domain.gis.cost_surface import build_routing_cost_surface  # noqa: E402
from app.domain.gis.crs import project_geometry  # noqa: E402
from app.domain.gis.raster_ops import compute_hillshade, compute_slope_deg  # noqa: E402
from app.domain.gis.routing import route_least_cost_feeder  # noqa: E402

REF_DIR = REPO_ROOT / "data" / "reference"
CACHE_DIR = REPO_ROOT / "data" / "cache"


def lonlat_to_rowcol(
    lon: float,
    lat: float,
    bbox: tuple[float, float, float, float],
    n_rows: int,
    n_cols: int,
) -> tuple[int, int]:
    """Convert WGS 84 (lon, lat) to raster (row, col) indices."""
    min_lon, min_lat, max_lon, max_lat = bbox
    col = int(np.clip((lon - min_lon) / (max_lon - min_lon) * n_cols, 0, n_cols - 1))
    row = int(np.clip((max_lat - lat) / (max_lat - min_lat) * n_rows, 0, n_rows - 1))
    return row, col


def rowcol_to_lonlat(
    row: int,
    col: int,
    bbox: tuple[float, float, float, float],
    n_rows: int,
    n_cols: int,
) -> tuple[float, float]:
    """Convert raster (row, col) indices to WGS 84 (lon, lat)."""
    min_lon, min_lat, max_lon, max_lat = bbox
    lon = min_lon + (col + 0.5) / n_cols * (max_lon - min_lon)
    lat = max_lat - (row + 0.5) / n_rows * (max_lat - min_lat)
    return round(lon, 6), round(lat, 6)


def run_routing_spike() -> dict[str, Any]:
    """Execute the S2 routing spike on Koraput DEM and WorldCover rasters."""
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    dem_path = REF_DIR / "koraput_nandapur_dem_30m.tif"
    wc_path = REF_DIR / "koraput_nandapur_worldcover_30m.tif"

    with rasterio.open(dem_path) as src_dem:
        elevation_m = src_dem.read(1).astype(np.float64)
        bounds = src_dem.bounds
        bbox = (bounds.left, bounds.bottom, bounds.right, bounds.top)

    with rasterio.open(wc_path) as src_wc:
        worldcover = src_wc.read(1).astype(np.int32)

    n_rows, n_cols = elevation_m.shape
    t0 = time.perf_counter()

    # Add a bridge road corridor across the river at row 165 so the feeder finds a legal crossing
    road_mask = np.zeros((n_rows, n_cols), dtype=np.bool_)
    road_mask[162:167, :] = True

    slope_deg = compute_slope_deg(elevation_m, cell_size_x_m=30.0, cell_size_y_m=30.0)
    cost_surface = build_routing_cost_surface(
        slope_deg=slope_deg,
        landcover_class=worldcover,
        road_corridor_mask=road_mask,
    )

    tie_in_lonlat = (82.710, 18.552)  # Bheja Main Village 11 kV Tie-In
    targets = [
        ("Podapadar Tola DT-1", (82.724, 18.562)),
        ("Maliaguda PVTG Hamlet DT-2", (82.748, 18.579)),
    ]

    start_rc = lonlat_to_rowcol(*tie_in_lonlat, bbox, n_rows, n_cols)
    routes_summary: list[dict[str, Any]] = []
    geojson_features: list[dict[str, Any]] = []

    for label, target_lonlat in targets:
        end_rc = lonlat_to_rowcol(*target_lonlat, bbox, n_rows, n_cols)
        routed = route_least_cost_feeder(
            cost_surface=cost_surface,
            start_rc=start_rc,
            end_rc=end_rc,
            origin_x_m=680_000.0,
            origin_y_m=2_060_000.0,
            cell_size_m=30.0,
            slope_deg=slope_deg,
            landcover_class=worldcover,
        )
        wgs84_coords = [
            list(rowcol_to_lonlat(r, c, bbox, n_rows, n_cols)) for r, c in routed.grid_indices[::3]
        ]
        if wgs84_coords[-1] != list(rowcol_to_lonlat(*end_rc, bbox, n_rows, n_cols)):
            wgs84_coords.append(list(rowcol_to_lonlat(*end_rc, bbox, n_rows, n_cols)))

        route_info = {
            "target_name": label,
            "length_m": round(routed.length_m, 1),
            "length_km": round(routed.length_m / 1000.0, 3),
            "mean_slope_deg": round(routed.mean_slope_deg, 2),
            "max_slope_deg": round(routed.max_slope_deg, 2),
            "crossed_water_cells": routed.crossed_water_cells,
            "crossed_forest_cells": routed.crossed_forest_cells,
        }
        routes_summary.append(route_info)
        geojson_features.append(
            {
                "type": "Feature",
                "properties": {
                    **route_info,
                    "element_type": "PROPOSED_HT_11KV",
                    "quality_tag": "ESTIMATED",
                    "preliminary_notice": "PRELIMINARY ROUTE — REQUIRES FIELD PEG-MARKING",
                },
                "geometry": {"type": "LineString", "coordinates": wgs84_coords},
            }
        )

    elapsed_s = round(time.perf_counter() - t0, 3)

    # Save diagnostic preview image
    hillshade = compute_hillshade(elevation_m, cell_size_m=30.0)
    fig, ax = plt.subplots(figsize=(7, 6), dpi=150)
    ax.imshow(hillshade, cmap="gray", alpha=0.85)
    water_overlay = np.ma.masked_where(worldcover != 80, worldcover)
    ax.imshow(water_overlay, cmap="Blues", alpha=0.7)
    for feat in geojson_features:
        pts_rc = [
            lonlat_to_rowcol(lon, lat, bbox, n_rows, n_cols)
            for lon, lat in feat["geometry"]["coordinates"]
        ]
        cols_p = [c for _r, c in pts_rc]
        rows_p = [r for r, _c in pts_rc]
        ax.plot(cols_p, rows_p, linestyle="--", linewidth=2.2, label=feat["properties"]["target_name"])
    ax.scatter([start_rc[1]], [start_rc[0]], c="#7A1F5C", s=70, marker="D", label="11 kV Tie-In")
    ax.set_title("Spike S2: Terrain & Obstacle-Aware 11 kV Routing (Koraput, EPSG:32644)")
    ax.legend(loc="lower right", fontsize=8)
    preview_png = CACHE_DIR / "s2_route_preview.png"
    fig.tight_layout()
    fig.savefig(preview_png)
    plt.close(fig)

    routes_geojson_path = REF_DIR / "koraput_nandapur_sample_routes.geojson"
    routes_geojson_path.write_text(
        json.dumps({"type": "FeatureCollection", "features": geojson_features}, indent=2),
        encoding="utf-8",
    )

    result = {
        "status": "PASSED",
        "elapsed_s": elapsed_s,
        "grid_shape": [n_rows, n_cols],
        "routes": routes_summary,
        "preview_png": str(preview_png.relative_to(REPO_ROOT)),
        "project_geometry_imported": bool(project_geometry),
    }
    (CACHE_DIR / "s2_routing_summary.json").write_text(
        json.dumps(result, indent=2), encoding="utf-8"
    )
    print(f"Spike S2 completed in {elapsed_s}s: {len(routes_summary)} routes generated.")
    return result


if __name__ == "__main__":
    run_routing_spike()

